import sys
import random
import math

def main():
    q = [random.randrange(1, 9) for _ in range(8)]
    T = 100.0
    cooling = 0.95
    iteration = 1

    def cost(q):
        return sum(q[i] == q[j] or abs(q[i]-q[j]) == j-i
                   for i in range(8) for j in range(i+1, 8))

    def board(q):
        for r in range(1, 9):
            print(" ".join("Q" if q[c] == r else "." for c in range(8)))
        print("Cost =", cost(q))

    while cost(q) != 0:
        if T <= 0.01:
            print("\nRestarting...")
            q = [random.randrange(1, 9) for _ in range(8)]
            T = 100.0

        print("\nIteration:", iteration)
        print("Current state:", q)
        print("Current board:")
        board(q)
        print("Temperature:", round(T, 4))

        t = q[:]
        c = random.randrange(8)
        r = random.randrange(1, 9)
        while r == q[c]:
            r = random.randrange(1, 9)
        t[c] = r

        print("\nNeighbor state:", t)
        print("Neighbor board:")
        board(t)

        old, new = cost(q), cost(t)
        delta = new - old
        print("Neighbor cost:", new)

        if delta < 0:
            q = t
            print("Decision: Accepted (better state)")
        else:
            p = math.exp(-delta / T)
            x = random.random()
            print("Acceptance probability:", round(p, 4))
            print("Random number:", round(x, 4))

            if x < p:
                q = t
                print("Decision: Accepted")
            else:
                print("Decision: Rejected")

        print("\nSelected state:", q)
        print("Selected board:")
        board(q)

        T *= cooling
        iteration += 1

    print("\nFinal 8-Queens Solution:")
    board(q)
    print("Cost = 0")

if __name__ == "__main__":
    main()