def unify(a, b):
    def parse(s):
        p, args = s.split("(")
        return p.strip(), [i.strip() for i in args[:-1].split(",")]

    p1, x = parse(a)
    p2, y = parse(b)

    if p1 != p2 or len(x) != len(y):
        return "FAILURE"

    s = {}

    for a, b in zip(x, y):
        a = s.get(a, a)
        b = s.get(b, b)

        if a == b:
            continue
        elif len(a) == 1 and a.islower():
            s[a] = b
        elif len(b) == 1 and b.islower():
            s[b] = a
        else:
            return "FAILURE"

    return s


a = input("Enter first expression: ")
b = input("Enter second expression: ")

print("Substitution:", unify(a, b))