from itertools import product

kb = input("Enter Knowledge Base: ")
q = input("Enter Query: ")

def convert(s):
    s = s.replace("~", " not ")
    s = s.replace("&", " and ")
    s = s.replace("|", " or ")
    return s

kb = convert(kb)
q = convert(q)

symbols = sorted(set(c for c in kb + q if c.isupper()))

print("\nTruth Table:")
print(*symbols, "KB", "Query", sep="\t")

entails = True

for values in product([True, False], repeat=len(symbols)):
    m = dict(zip(symbols, values))

    k = eval(kb, {"__builtins__": {}}, m)
    query = eval(q, {"__builtins__": {}}, m)

    print(*values, k, query, sep="\t")

    if k and not query:
        entails = False

if entails:
    print("\nKB entails Query")
else:
    print("\nKB does NOT entail Query")