import sys
import random

def main():
    q = [random.randrange(1, 5) for _ in range(4)]
    iteration = 1

    def cost(q):
        return sum(q[i] == q[j] or abs(q[i]-q[j]) == j-i
                   for i in range(4) for j in range(i+1, 4))

    def board(q):
        for r in range(1, 5):
            print(" ".join("Q" if q[c] == r else "." for c in range(4)))
        print("Cost =", cost(q))

    while cost(q) != 0:
        print("\nIteration:", iteration)
        print("Current state:", q)
        print("Current board:")
        board(q)

        best, m = q[:], cost(q)

        for c in range(4):
            for r in range(1, 5):
                if q[c] == r:
                    continue
                t = q[:]
                t[c] = r
                print("\nNeighbor:", t, "Cost:", cost(t))
                board(t)

                if cost(t) < m:
                    best, m = t, cost(t)

        if best == q:
            print("\nLocal minimum reached. Restarting...")
            q = [random.randrange(1, 5) for _ in range(4)]
        else:
            q = best

        print("\nSelected state:", q)
        print("Selected board:")
        board(q)
        iteration += 1

    print("\nFinal Solution:")
    board(q)

if __name__ == "__main__":
    main()