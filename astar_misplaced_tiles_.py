import sys
import heapq

def main():
    s = (2,8,3,1,6,4,7,0,5)
    goal = (1,2,3,0,8,4,7,6,5)

    def h(s):
        return sum(s[i] != goal[i] and s[i] != 0 for i in range(9))

    pq = [(h(s), 0, s)]
    best = {s: 0}

    while pq:
        f, g, s = heapq.heappop(pq)
        if g != best[s]:
            continue

        print("S =", list(s), "g(n) =", g,
              "h(n) =", h(s), "f(n) =", f)
        for i in range(0, 9, 3):
            print(*s[i:i+3])
        print()

        if s == goal:
            print("Goal reached")
            return

        z = s.index(0)
        for d in (-3, 3, -1, 1):
            n = z + d
            if n < 0 or n >= 9 or (d == -1 and z % 3 == 0) or (d == 1 and z % 3 == 2):
                continue

            t = list(s)
            t[z], t[n] = t[n], t[z]
            t = tuple(t)
            ng = g + 1

            if ng < best.get(t, float('inf')):
                best[t] = ng
                heapq.heappush(pq, (ng + h(t), ng, t))

    print("No solution")

if __name__ == "__main__":
    main()